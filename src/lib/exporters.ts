export interface ExportBundle {
  event: EventRecord;
  budget: BudgetCalculationResult | null;
  tasks: TaskRecord[];
  vendors: VendorRecord[];
  rsvps: GuestRsvpRecord[];
  budgetItems: BudgetItemRecord[];
}

const money = (n: number, cur = 'USD') =>
  new Intl.NumberFormat('en-US', { style: 'currency', currency: cur, maximumFractionDigits: 0 }).format(
    Number.isFinite(n) ? n : 0
  );

/** Escapes a CSV cell and neutralises spreadsheet formula injection. */
export function csvCell(value: unknown): string {
  let s = value === null || value === undefined ? '' : String(value);
  if (/^[=+\-@\t\r]/.test(s)) s = `'${s}`;
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export function toCsv(rows: unknown[][]): string {
  return rows.map((r) => r.map(csvCell).join(',')).join('\r\n');
}

export function buildBudgetCsv(b: ExportBundle): string {
  const rows: unknown[][] = [
    ['Category', 'Item', 'Unit cost', 'Qty', 'Per guest', 'Tax %', 'Contingency %', 'Projected total', 'Actual', 'Status'],
  ];
  const computed = b.budget?.items ?? [];
  for (const i of computed) {
    rows.push([
      i.category, i.name, i.unit_cost, i.effective_quantity, i.is_per_guest ? 'yes' : 'no',
      i.tax_pct, i.contingency_pct, i.deterministic_total, i.actual_cost, i.status,
    ]);
  }
  return toCsv(rows);
}

export function buildGuestCsv(b: ExportBundle): string {
  const rows: unknown[][] = [['Guest', 'Contact', 'Party size', 'RSVP', 'Dietary', 'Table', 'Tag']];
  for (const r of b.rsvps) {
    rows.push([r.guest_name, r.contact, r.party_size, r.status, r.dietary_requirements, r.seating_table, r.vip_tag ?? '']);
  }
  return toCsv(rows);
}

/** Human-readable plan summary (Markdown) that doubles as a printable document. */
export function buildPlanMarkdown(b: ExportBundle): string {
  const { event, budget, tasks, vendors, rsvps } = b;
  const cur = event.currency || 'USD';
  const L: string[] = [];
  L.push(`# ${event.title}`);
  L.push('');
  L.push(`**Type:** ${event.event_type} · **Date:** ${event.date} · **Location:** ${event.location}`);
  L.push(`**Guests:** ${event.guest_count} · **Target budget:** ${money(event.target_budget, cur)}`);
  L.push('');
  if (budget) {
    L.push('## Budget');
    L.push(`- Projected spend: **${money(budget.totalProjectedSpend, cur)}** (${budget.burnRatePct}% of target)`);
    L.push(`- Remaining: ${money(budget.remainingBudget, cur)} · Cost per guest: ${money(budget.costPerGuest, cur)}`);
    L.push('');
    L.push('| Category | Allocated | Share |');
    L.push('|---|---:|---:|');
    for (const c of budget.categories) {
      L.push(`| ${c.category} | ${money(c.allocated_total, cur)} | ${c.share_pct}% |`);
    }
    L.push('');
  }
  L.push('## Timeline');
  const sorted = [...tasks].sort((a, b2) => (a.due_date || '').localeCompare(b2.due_date || ''));
  for (const t of sorted) {
    L.push(`- [${t.status === 'completed' ? 'x' : ' '}] **${t.due_date}** — ${t.title}${t.is_critical_path ? ' _(critical path)_' : ''} · ${t.assigned_to}`);
  }
  if (sorted.length === 0) L.push('_No tasks yet._');
  L.push('');
  L.push('## Vendors');
  for (const v of vendors) {
    L.push(`- **${v.name}** (${v.service_type}) — ${v.status}, true cost ${money(v.parsed_terms?.total_true_cost ?? v.quote_amount, cur)}`);
  }
  if (vendors.length === 0) L.push('_No vendors yet._');
  L.push('');
  const confirmed = rsvps.filter((r) => r.status === 'confirmed').reduce((s, r) => s + r.party_size, 0);
  L.push('## Guests');
  L.push(`${confirmed} confirmed of ${event.guest_count} planned across ${rsvps.length} invitations.`);
  L.push('');
  L.push(`_Generated by PlanGenie on ${new Date().toISOString().slice(0, 10)}_`);
  return L.join('\n');
}

