// iCalendar (.ics) — works with Google/Apple/Outlook with zero API keys.
// ---------------------------------------------------------------------------

function icsEscape(s: string): string {
  return String(s ?? '')
    .replace(/\\/g, '\\\\')
    .replace(/;/g, '\\;')
    .replace(/,/g, '\\,')
    .replace(/\r?\n/g, '\\n');
}

/** Folds lines to 75 octets as required by RFC 5545. */
function foldLine(line: string): string {
  const out: string[] = [];
  let cur = '';
  let bytes = 0;
  for (const ch of line) {
    const b = new TextEncoder().encode(ch).length;
    if (bytes + b > 74) {
      out.push(cur);
      cur = ' ' + ch;
      bytes = 1 + b;
    } else {
      cur += ch;
      bytes += b;
    }
  }
  out.push(cur);
  return out.join('\r\n');
}

const compactDate = (iso: string) => iso.replace(/-/g, '');

export function buildIcs(b: ExportBundle, nowIso: string = new Date().toISOString()): string {
  const { event, tasks } = b;
  const stamp = nowIso.replace(/[-:]/g, '').replace(/\.\d+/, '');
  const days = Math.max(1, event.event_days ?? 1);
  const lines: string[] = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//PlanGenie//Event Planner//EN',
    'CALSCALE:GREGORIAN',
    'METHOD:PUBLISH',
    `X-WR-CALNAME:${icsEscape(event.title)}`,
    'BEGIN:VEVENT',
    `UID:${event.id}@plangenie`,
    `DTSTAMP:${stamp}`,
    `DTSTART;VALUE=DATE:${compactDate(event.date)}`,
    `DTEND;VALUE=DATE:${compactDate(addDaysIso(event.date, days))}`,
    `SUMMARY:${icsEscape(event.title)}`,
    `LOCATION:${icsEscape(event.location)}`,
    `DESCRIPTION:${icsEscape(`${event.guest_count} guests · planned with PlanGenie`)}`,
    'END:VEVENT',
  ];
  for (const t of tasks) {
    if (!t.due_date) continue;
    lines.push(
      'BEGIN:VEVENT',
      `UID:${t.id}@plangenie`,
      `DTSTAMP:${stamp}`,
      `DTSTART;VALUE=DATE:${compactDate(t.due_date)}`,
      `DTEND;VALUE=DATE:${compactDate(addDaysIso(t.due_date, 1))}`,
      `SUMMARY:${icsEscape(`${t.status === 'completed' ? '✓ ' : ''}${t.title}`)}`,
      `DESCRIPTION:${icsEscape(`${event.title} · ${t.category} · owner: ${t.assigned_to}`)}`,
      'BEGIN:VALARM',
      'TRIGGER:-P1D',
      'ACTION:DISPLAY',
      `DESCRIPTION:${icsEscape(t.title)}`,
      'END:VALARM',
      'END:VEVENT'
    );
  }
  lines.push('END:VCALENDAR');
  return lines.map(foldLine).join('\r\n') + '\r\n';
}

export function safeFilename(name: string, ext: string): string {
  const base =
    name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 60) || 'plangenie-event';
  return `${base}.${ext}`;
}

/** Browser-only: triggers a file download. Returns false if unavailable. */
export function downloadTextFile(filename: string, content: string, mime: string): boolean {
  try {
    const blob = new Blob([content], { type: `${mime};charset=utf-8` });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
    return true;
  } catch {
    return false;
  }
}
